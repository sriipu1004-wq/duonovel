/** Normalize layout-oriented Unicode glyphs into ordinary horizontal prose. */
export function normalizeImportedText(value: string): string {
  return value
    .replace(/^\uFEFF/u, "")
    .replace(/\u0000/gu, "")
    .replace(/\r\n?/gu, "\n")
    .replace(/[\t\u00a0]+/gu, " ")
    .replace(/︐/gu, "，")
    .replace(/︑/gu, "、")
    .replace(/︒/gu, "。")
    .replace(/︓/gu, "：")
    .replace(/︔/gu, "；")
    .replace(/︕/gu, "！")
    .replace(/︖/gu, "？")
    .replace(/[︵﹙]/gu, "（")
    .replace(/[︶﹚]/gu, "）")
    .replace(/︷/gu, "｛")
    .replace(/︸/gu, "｝")
    .replace(/︹/gu, "〔")
    .replace(/︺/gu, "〕")
    .replace(/︻/gu, "【")
    .replace(/︼/gu, "】")
    .replace(/︽/gu, "《")
    .replace(/︾/gu, "》")
    .replace(/︿/gu, "〈")
    .replace(/﹀/gu, "〉")
    .replace(/﹁/gu, "「")
    .replace(/﹂/gu, "」")
    .replace(/﹃/gu, "『")
    .replace(/﹄/gu, "』")
    .replace(/﹛/gu, "｛")
    .replace(/﹜/gu, "｝")
    .replace(/﹝/gu, "〔")
    .replace(/﹞/gu, "〕")
    .replace(/︙︙/gu, "……")
    .replace(/︙/gu, "…")
    .replace(/[│︱]{2,}/gu, "――")
    .replace(/[ \u3000]+$/gmu, "")
    .replace(/\n{4,}/gu, "\n\n\n")
    .trim();
}
