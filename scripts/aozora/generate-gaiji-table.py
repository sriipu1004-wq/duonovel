# Generate src/lib/aozora/aozoraGaijiGenerated.ts from scripts/aozora/gaiji-pairs.tsv.
#
# Each line is "<plane>-<row>-<cell>\t<Aozora description>" as it appears in
# published Aozora texts (※［＃「…」、第3水準1-86-44］). The character is
# derived from the JIS X 0213 code with Python's euc_jisx0213 codec, the same
# verification used for the hand-checked entries in aozoraNotation.ts.
# A code that appears with two different descriptions is skipped (one of the
# two is an Aozora typo we cannot settle mechanically), so it stays literal,
# unless scripts/aozora/gaiji-equivalent.tsv lists the code as reviewed
# (same structure, different wording); then every description is accepted.
#   PYTHONIOENCODING=utf-8 python scripts/aozora/generate-gaiji-table.py
import collections
import json

equivalent = set()
with open("scripts/aozora/gaiji-equivalent.tsv", encoding="utf8") as handle:
    for line in handle:
        line = line.strip()
        if line and not line.startswith("#"):
            equivalent.add(line)

pairs = collections.defaultdict(set)
with open("scripts/aozora/gaiji-pairs.tsv", encoding="utf8") as handle:
    for line in handle:
        line = line.rstrip("\n")
        if not line:
            continue
        code, description = line.split("\t")
        pairs[code].add(description)


def decode(code: str) -> str:
    plane, row, cell = (int(part) for part in code.split("-"))
    raw = bytes([0xA0 + row, 0xA0 + cell])
    if plane == 2:
        raw = b"\x8f" + raw
    return raw.decode("euc_jisx0213")


entries = []
skipped = []
for code in sorted(pairs, key=lambda c: tuple(int(p) for p in c.split("-"))):
    descriptions = pairs[code]
    if len(descriptions) != 1 and code not in equivalent:
        skipped.append((code, sorted(descriptions)))
        continue
    char = decode(code)
    if len(char) != 1 or ord(char) < 0x80 or char == "�":
        skipped.append((code, sorted(descriptions)))
        continue
    entries.append((code, sorted(descriptions), char))

lines = [
    "// GENERATED by scripts/aozora/generate-gaiji-table.py from",
    "// scripts/aozora/gaiji-pairs.tsv. Do not edit by hand.",
    "// Code -> character via JIS X 0213 (Python euc_jisx0213); the Aozora",
    "// description must match one of the listed descriptions exactly at lookup time.",
    "export const AOZORA_GENERATED_GAIJI: Readonly<",
    "  Record<string, { descriptions: readonly string[]; char: string }>",
    "> = {",
]
for code, descriptions, char in entries:
    lines.append(f"  {json.dumps(code)}: {{ descriptions: {json.dumps(descriptions, ensure_ascii=False)}, char: {json.dumps(char, ensure_ascii=False)} }},")
lines.append("};")
lines.append("")
with open("src/lib/aozora/aozoraGaijiGenerated.ts", "w", encoding="utf8", newline="\n") as handle:
    handle.write("\n".join(lines))
print(f"entries={len(entries)} skipped={len(skipped)}")
for code, descriptions in skipped:
    print("skipped", code, descriptions)
