# Issue #139 batch 4: generate the publish SQL (apply.sql / rollback.sql) for
# the 100 Aozora works without a per-country restriction
# (docs/rights/pd-batch-2026-11-aozora-4.md).
#
# Same publish/rollback logic, guards and snapshot shape as the reviewed
# batch-3 SQL (scripts/issue139-aozora-publish-batch3/), with one difference:
# batch 3 was generated after the import and listed series ids; this batch is
# generated before the import, so each series is found by
# effect_settings.publicDomain.manifestId (exactly one series per manifest, as
# in scripts/public-domain/region-publish-sql.ts). Expected chapter counts and
# content warnings come from the manifests.
#   PYTHONIOENCODING=utf-8 python scripts/issue139-aozora-publish-batch4/generate.py <ids.txt>
import json
import os
import sys

OUT = os.path.dirname(os.path.abspath(__file__))
TAG = "issue139_publish4"
DATE = "20261119"
CODE = "ISSUE139_BATCH4"
SERIES = f"libread_internal.{TAG}_series_{DATE}"
EPISODES = f"libread_internal.{TAG}_episodes_{DATE}"

ids = open(sys.argv[1], encoding="utf8").read().split()
assert len(ids) == len(set(ids)), "duplicate ids"
rows = []
for manifest_id in sorted(ids):
    m = json.load(open(f"public-domain/manifests/{manifest_id}.json", encoding="utf8"))
    assert m["approved"] is True and m["rights_status"] == "approved", manifest_id
    assert not m.get("region_restriction"), f"{manifest_id}: region-restricted works use region-publish-sql.ts"
    assert m["source_provider"] == "Aozora Bunko", manifest_id
    assert isinstance(m.get("content_warnings"), list), manifest_id
    rows.append((manifest_id, int(m["chapter_count"]), sorted(m["content_warnings"])))
N = len(rows)
E = sum(r[1] for r in rows)


def arr(values):
    return "array[" + ",".join(f"'{v}'" for v in values) + "]::text[]"


values = ",\n  ".join(f"('{mid}', {n}, {arr(w)})" for mid, n, w in rows)
id_list = ",\n  ".join(f"'{mid}'" for mid, _, _ in rows)

header = f"""-- GENERATED by scripts/issue139-aozora-publish-batch4/generate.py ({N} works,
-- {E} chapters; docs/rights/pd-batch-2026-11-aozora-4.md). Same logic as the
-- batch-3 SQL, but series are resolved by publicDomain.manifestId because this
-- file is generated before the import. Do not edit by hand; regenerate.
-- Publication needs the owner's button approval (not given when generated).
"""

apply_sql = f"""{header}--
-- Changes exactly what the author's publish flow changes, and nothing else:
--   series   : publication_status 'private' -> 'public', is_public false -> true
--   episodes : posting_status 'draft' -> 'posted', is_published false -> true,
--              posted_at null -> now() (saveOwnedEpisode sets posted_at on
--              first posting; last_edited_at stays null; scheduled_for stays null)
-- Rights metadata (effect_settings.publicDomain), content_rating,
-- content_warnings, permissions, tags, genres, titles and bodies are untouched.
--
-- Every previous value is stored first in libread_internal so rollback.sql
-- can restore it exactly. Run once, in one transaction.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';

create temporary table issue139_batch4_targets (
  manifest_id text primary key,
  expected_episodes integer not null check (expected_episodes > 0),
  expected_warnings text[] not null
) on commit drop;
insert into issue139_batch4_targets values
  {values};

-- Serialize against concurrent edits of these {N} series for this transaction.
select s.id from public.series s
where s.effect_settings->'publicDomain'->>'manifestId' in (
  {id_list})
for update;

create schema if not exists libread_internal;
create table {SERIES} (
  series_id uuid primary key,
  manifest_id text not null unique,
  expected_episodes integer not null,
  expected_warnings text[] not null,
  is_public_before boolean,
  publication_status_before text not null
);
create table {EPISODES} (
  episode_id uuid primary key,
  series_id uuid not null,
  episode_number integer not null,
  is_published_before boolean not null,
  posting_status_before text not null,
  scheduled_for_before timestamptz,
  posted_at_before timestamptz,
  last_edited_at_before timestamptz,
  posted_at_after timestamptz
);
alter table {SERIES} enable row level security;
alter table {EPISODES} enable row level security;
revoke all on {SERIES} from public, anon, authenticated;
revoke all on {EPISODES} from public, anon, authenticated;

-- One series per manifest (a duplicate series_id or manifest_id aborts here).
insert into {SERIES}
  (series_id, manifest_id, expected_episodes, expected_warnings,
   is_public_before, publication_status_before)
select s.id, t.manifest_id, t.expected_episodes, t.expected_warnings,
       s.is_public, s.publication_status
from issue139_batch4_targets t
join public.series s on s.effect_settings->'publicDomain'->>'manifestId' = t.manifest_id;

insert into {EPISODES}
  (episode_id, series_id, episode_number, is_published_before, posting_status_before,
   scheduled_for_before, posted_at_before, last_edited_at_before)
select e.id, e.series_id, e.episode_number, e.is_published, e.posting_status,
       e.scheduled_for, e.posted_at, e.last_edited_at
from public.episodes e
join {SERIES} t on t.series_id = e.series_id;

-- Guards: exact scope and the current private Draft state; abort on drift.
do $$ begin
  if (select count(*) from {SERIES}) <> {N} then
    raise exception '{CODE}_PUBLISH_SERIES_COUNT_MISMATCH';
  end if;
  if (select count(*) from {EPISODES}) <> {E} then
    raise exception '{CODE}_PUBLISH_EPISODE_COUNT_MISMATCH';
  end if;
  -- Series: private, general rating, reviewed Aozora rights metadata for the
  -- expected manifest, the owner-approved content warnings, one account,
  -- and no region restriction row (these works need none).
  if exists (
    select 1
    from {SERIES} t
    join public.series s on s.id = t.series_id
    where s.publication_status <> 'private'
       or s.is_public is distinct from false
       or s.content_rating <> 'general'
       or not (s.content_warnings @> t.expected_warnings and s.content_warnings <@ t.expected_warnings)
       or s.effect_settings->'publicDomain'->>'rightsChecked' is distinct from 'true'
       or s.effect_settings->'publicDomain'->>'manifestId' is distinct from t.manifest_id
       or s.effect_settings->'publicDomain'->>'sourceProvider' is distinct from 'Aozora Bunko'
  ) then raise exception '{CODE}_PUBLISH_SERIES_STATE_DRIFT'; end if;
  if (select count(distinct s.author_id)
      from {SERIES} t
      join public.series s on s.id = t.series_id) <> 1 then
    raise exception '{CODE}_PUBLISH_AUTHOR_DRIFT';
  end if;
  if exists (
    select 1 from {SERIES} t
    join public.series_region_restrictions r on r.series_id = t.series_id
  ) then raise exception '{CODE}_PUBLISH_UNEXPECTED_REGION_RESTRICTION'; end if;
  -- Episodes: all Draft, never posted, numbered 1..n with the expected n.
  if exists (
    select 1 from {EPISODES}
    where posting_status_before <> 'draft' or is_published_before
       or scheduled_for_before is not null or posted_at_before is not null
  ) then raise exception '{CODE}_PUBLISH_EPISODE_STATE_DRIFT'; end if;
  if exists (
    select 1
    from {SERIES} t
    left join {EPISODES} e on e.series_id = t.series_id
    group by t.series_id, t.expected_episodes
    having count(e.episode_id) <> t.expected_episodes
        or min(e.episode_number) <> 1
        or max(e.episode_number) <> t.expected_episodes
  ) then raise exception '{CODE}_PUBLISH_EPISODE_NUMBERING_DRIFT'; end if;
end $$;

do $$
declare
  v_series integer;
  v_episodes integer;
begin
  update public.series s
    set publication_status = 'public', is_public = true
  from {SERIES} t
  where s.id = t.series_id
    and s.publication_status = 'private' and s.is_public = false;
  get diagnostics v_series = row_count;
  if v_series <> {N} then
    raise exception '{CODE}_PUBLISH_SERIES_ROWCOUNT_MISMATCH %', v_series;
  end if;

  update public.episodes e
    set posting_status = 'posted', is_published = true, posted_at = now()
  from {EPISODES} t
  where e.id = t.episode_id
    and e.posting_status = 'draft' and e.is_published = false and e.posted_at is null;
  get diagnostics v_episodes = row_count;
  if v_episodes <> {E} then
    raise exception '{CODE}_PUBLISH_EPISODE_ROWCOUNT_MISMATCH %', v_episodes;
  end if;

  update {EPISODES} t
    set posted_at_after = e.posted_at
  from public.episodes e
  where e.id = t.episode_id;

  -- The public read boundary (RLS policy + public_episode_work_summaries)
  -- must now expose exactly these {N} works with {E} chapters.
  if (select count(*) from public.public_episode_work_summaries v
      join {SERIES} t on t.series_id = v.series_id
      where v.episode_count = t.expected_episodes) <> {N} then
    raise exception '{CODE}_PUBLISH_PUBLIC_VIEW_MISMATCH';
  end if;
end $$;
commit;

-- After commit (no SQL needed): the public catalog cache
-- (unstable_cache tag public-base-work-cards) and sitemap revalidate every
-- 60 s; the Work page, Reader and RLS read the DB directly. Wait at least
-- 60 s, then check /search, the {N} /works/<id> pages, one Reader page per
-- work and /sitemap.xml on Production.
"""

rollback_sql = f"""{header}--
-- Exact revert of apply.sql (back to private Drafts). Restores every stored
-- previous value (publication_status, is_public, posting_status, is_published,
-- scheduled_for, posted_at, last_edited_at) for the {N} series / {E} episodes
-- recorded by apply.sql, then drops the snapshot tables. Nothing is deleted
-- from public tables: bookmarks, views, reviews, translations or recordings
-- created while public stay in place and become non-public through the
-- existing private/draft read boundary.
--
-- Aborts (no change) if any row was edited after apply.sql: a different
-- posted_at, a set last_edited_at, a scheduled episode or another
-- publication state. Resolve that case by hand; do not force it.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';

select s.id from public.series s
join {SERIES} t on t.series_id = s.id
for update of s;

do $$ begin
  -- Snapshot scope must be exactly what apply.sql recorded.
  if (select count(*) from {SERIES}) <> {N}
     or (select count(*) from {EPISODES}) <> {E}
     or exists (
       select 1 from {SERIES}
       where manifest_id not in (
  {id_list}))
     or exists (
       select 1 from {EPISODES} e
       where e.series_id not in (select series_id from {SERIES}))
  then raise exception '{CODE}_ROLLBACK_SNAPSHOT_SCOPE_MISMATCH'; end if;

  -- Current state must still be exactly what apply.sql left.
  if exists (
    select 1
    from {SERIES} t
    left join public.series s on s.id = t.series_id
    where s.id is null or s.publication_status <> 'public' or s.is_public is distinct from true
  ) then raise exception '{CODE}_ROLLBACK_SERIES_STATE_DRIFT'; end if;
  if exists (
    select 1
    from {EPISODES} t
    left join public.episodes e on e.id = t.episode_id
    where e.id is null
       or e.series_id <> t.series_id
       or e.posting_status <> 'posted' or e.is_published is distinct from true
       or e.scheduled_for is not null
       or t.posted_at_after is null or e.posted_at is distinct from t.posted_at_after
       or e.last_edited_at is distinct from t.last_edited_at_before
  ) then raise exception '{CODE}_ROLLBACK_EPISODE_STATE_DRIFT'; end if;
  if (select count(*) from public.episodes e
      join {SERIES} t on t.series_id = e.series_id) <> {E} then
    raise exception '{CODE}_ROLLBACK_EPISODE_SET_CHANGED';
  end if;
end $$;

do $$
declare
  v_series integer;
  v_episodes integer;
begin
  update public.episodes e
    set posting_status = t.posting_status_before,
        is_published = t.is_published_before,
        scheduled_for = t.scheduled_for_before,
        posted_at = t.posted_at_before,
        last_edited_at = t.last_edited_at_before
  from {EPISODES} t
  where e.id = t.episode_id and e.posted_at = t.posted_at_after;
  get diagnostics v_episodes = row_count;
  if v_episodes <> {E} then
    raise exception '{CODE}_ROLLBACK_EPISODE_ROWCOUNT_MISMATCH %', v_episodes;
  end if;

  update public.series s
    set publication_status = t.publication_status_before,
        is_public = t.is_public_before
  from {SERIES} t
  where s.id = t.series_id and s.publication_status = 'public';
  get diagnostics v_series = row_count;
  if v_series <> {N} then
    raise exception '{CODE}_ROLLBACK_SERIES_ROWCOUNT_MISMATCH %', v_series;
  end if;

  if exists (select 1 from public.public_episode_work_summaries v
             join {SERIES} t on t.series_id = v.series_id) then
    raise exception '{CODE}_ROLLBACK_STILL_PUBLIC';
  end if;
end $$;

drop table {EPISODES};
drop table {SERIES};
commit;

-- After commit: RLS hides the works and chapters immediately; the cached
-- catalog/search cards and sitemap drop them within 60 s (revalidate: 60).
"""

for name, text in (("apply.sql", apply_sql), ("rollback.sql", rollback_sql)):
    with open(os.path.join(OUT, name), "w", encoding="utf8", newline="\n") as handle:
        handle.write(text)
print("series", N, "episodes", E)
