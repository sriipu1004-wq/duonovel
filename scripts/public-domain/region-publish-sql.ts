// Generate the publish SQL (apply / rollback / restrictions-only) for
// Public Domain works that carry a D030 region_restriction.
//
// Run AFTER batch.ts imported the works as private Drafts. The SQL finds each
// series by effect_settings.publicDomain.manifestId (exactly one per manifest)
// and, in ONE transaction, writes the public.series_region_restrictions row
// for every work and only then publishes it. A work whose restriction row is
// missing or differs is never published (the transaction aborts).
//
// Cache note (D030): the app reads restrictions through a 60 s in-process
// copy. If apply.sql inserts the rows itself, a just-published work can be
// served without its restriction for up to 60 s. To close that window, run
// restrictions.sql first, wait at least 2 minutes, then run apply.sql
// generated with --min-restriction-age-seconds=120 (apply.sql then refuses
// rows younger than that).
//
//   node --import tsx scripts/public-domain/region-publish-sql.ts \
//     --tag=<snake_case_tag> --out=<dir> [--min-restriction-age-seconds=N] \
//     <manifest-id>... | --all-region-restricted
//
// Writes <out>/restrictions.sql, <out>/apply.sql, <out>/rollback.sql. Never
// connects to a database.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { validateManifest, type PublicDomainManifest } from "./core";

export type RegionPublishTarget = {
  manifestId: string;
  title: string;
  sourceProvider: string;
  expectedEpisodes: number;
  expectedWarnings: string[];
  mode: "allow" | "block";
  countries: string[];
  reason: string;
};

export function regionPublishTargetFromManifest(
  manifest: PublicDomainManifest
): RegionPublishTarget {
  if (!manifest.approved || manifest.rights_status !== "approved") {
    throw new Error(`${manifest.id}: manifest is not approved`);
  }
  const restriction = manifest.region_restriction;
  if (!restriction) {
    throw new Error(`${manifest.id}: no region_restriction; this generator only publishes restricted works`);
  }
  if (!manifest.chapter_count) throw new Error(`${manifest.id}: chapter_count is missing`);
  if (manifest.content_warnings === undefined) {
    throw new Error(`${manifest.id}: content_warnings not reviewed`);
  }
  const authorSuffix = `・${manifest.original_author.trim()}`;
  const title = manifest.title.trim().endsWith(authorSuffix)
    ? manifest.title.trim()
    : `${manifest.title.trim()}${authorSuffix}`;
  const mode = "allowed_countries" in restriction ? "allow" : "block";
  const countries =
    "allowed_countries" in restriction ? restriction.allowed_countries : restriction.blocked_countries;
  for (const code of countries) {
    if (!/^[A-Z]{2}$/.test(code)) throw new Error(`${manifest.id}: invalid country code ${code}`);
  }
  return {
    manifestId: manifest.id,
    title,
    sourceProvider: manifest.source_provider,
    expectedEpisodes: manifest.chapter_count,
    expectedWarnings: [...manifest.content_warnings].sort(),
    mode,
    countries: [...countries],
    reason: `${manifest.id}: ${restriction.basis.trim()}`,
  };
}

function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function textArray(values: string[]): string {
  return values.length === 0 ? "array[]::text[]" : `array[${values.map(lit).join(",")}]::text[]`;
}

function targetsTableSql(targets: RegionPublishTarget[]): string {
  const rows = targets
    .map(
      (t) =>
        `  (${lit(t.manifestId)}, ${lit(t.title)}, ${lit(t.sourceProvider)}, ${t.expectedEpisodes}, ${textArray(
          t.expectedWarnings
        )}, ${lit(t.mode)}, ${textArray(t.countries)}, ${lit(t.reason)})`
    )
    .join(",\n");
  return `create temporary table pd_region_targets (
  manifest_id text primary key,
  expected_title text not null,
  source_provider text not null,
  expected_episodes integer not null check (expected_episodes > 0),
  expected_warnings text[] not null,
  mode text not null check (mode in ('allow', 'block')),
  countries text[] not null,
  reason text not null
) on commit drop;

insert into pd_region_targets values
${rows};`;
}

// The stored row must equal the expected list exactly (same list kind, same set).
const ROW_MATCHES = `(
      (t.mode = 'allow' and r.blocked_countries is null
        and r.allowed_countries @> t.countries and r.allowed_countries <@ t.countries)
   or (t.mode = 'block' and r.allowed_countries is null
        and r.blocked_countries @> t.countries and r.blocked_countries <@ t.countries)
    )`;

function header(tag: string, n: number, episodes: number, kind: string): string {
  return `-- Public Domain region-restricted publish (${kind}), tag ${tag}.
-- ${n} works / ${episodes} chapters. Generated by scripts/public-domain/region-publish-sql.ts.
-- Each publication and each restriction row needs the owner's button approval
-- and an independent review (D030). Do not edit by hand; regenerate.`;
}

export function buildRegionPublishSql(args: {
  tag: string;
  targets: RegionPublishTarget[];
  minRestrictionAgeSeconds?: number;
}): { restrictions: string; apply: string; rollback: string } {
  const { tag, targets } = args;
  if (!/^[a-z0-9_]{1,40}$/.test(tag)) throw new Error("tag must match ^[a-z0-9_]{1,40}$");
  if (targets.length === 0) throw new Error("no targets");
  const ids = new Set(targets.map((t) => t.manifestId));
  if (ids.size !== targets.length) throw new Error("duplicate manifest id");
  const minAge = args.minRestrictionAgeSeconds ?? 0;
  if (!Number.isInteger(minAge) || minAge < 0 || minAge > 86_400) {
    throw new Error("minRestrictionAgeSeconds must be an integer from 0 to 86400");
  }
  const n = targets.length;
  const episodes = targets.reduce((sum, t) => sum + t.expectedEpisodes, 0);
  const code = `PD_REGION_${tag.toUpperCase()}`;
  const seriesSnap = `libread_internal.pd_region_${tag}_series`;
  const episodeSnap = `libread_internal.pd_region_${tag}_episodes`;
  const targetsSql = targetsTableSql(targets);
  const manifestIdList = targets.map((t) => lit(t.manifestId)).join(", ");

  const resolveAndGuardSeries = `-- Resolve each manifest to exactly one series and lock it.
create temporary table pd_region_series on commit drop as
select t.manifest_id, s.id as series_id
from pd_region_targets t
join public.series s on s.effect_settings->'publicDomain'->>'manifestId' = t.manifest_id;

select s.id from public.series s
where s.effect_settings->'publicDomain'->>'manifestId' in (${manifestIdList})
for update;

do $$ begin
  if (select count(*) from pd_region_series) <> ${n}
     or (select count(distinct manifest_id) from pd_region_series) <> ${n}
     or (select count(distinct series_id) from pd_region_series) <> ${n} then
    raise exception '${code}_SERIES_RESOLVE_MISMATCH';
  end if;
  if exists (
    select 1
    from pd_region_targets t
    join pd_region_series m using (manifest_id)
    join public.series s on s.id = m.series_id
    where s.publication_status <> 'private'
       or s.is_public is distinct from false
       or s.content_rating <> 'general'
       or s.title <> t.expected_title
       or not (s.content_warnings @> t.expected_warnings and s.content_warnings <@ t.expected_warnings)
       or s.effect_settings->'publicDomain'->>'rightsChecked' is distinct from 'true'
       or s.effect_settings->'publicDomain'->>'sourceProvider' is distinct from t.source_provider
  ) then raise exception '${code}_SERIES_STATE_DRIFT'; end if;
  if (select count(distinct s.author_id) from pd_region_series m
      join public.series s on s.id = m.series_id) <> 1 then
    raise exception '${code}_AUTHOR_DRIFT';
  end if;
  -- An existing row must already be exactly the reviewed list.
  if exists (
    select 1 from pd_region_targets t
    join pd_region_series m using (manifest_id)
    join public.series_region_restrictions r on r.series_id = m.series_id
    where not ${ROW_MATCHES}
  ) then raise exception '${code}_EXISTING_RESTRICTION_DIFFERS'; end if;
end $$;`;

  const insertRestrictions = `insert into public.series_region_restrictions(series_id, blocked_countries, allowed_countries, reason)
select m.series_id,
       case when t.mode = 'block' then t.countries end,
       case when t.mode = 'allow' then t.countries end,
       t.reason
from pd_region_targets t
join pd_region_series m using (manifest_id)
where not exists (
  select 1 from public.series_region_restrictions r where r.series_id = m.series_id
);`;

  const allRowsPresent = (label: string) => `do $$ begin
  if (select count(*) from pd_region_targets t
      join pd_region_series m using (manifest_id)
      join public.series_region_restrictions r on r.series_id = m.series_id
      where ${ROW_MATCHES}) <> ${n} then
    raise exception '${code}_${label}';
  end if;
end $$;`;

  const restrictions = `${header(tag, n, episodes, "restrictions only")}
-- Writes series_region_restrictions only (no publication). Optional first
-- step: run this, wait at least 2 minutes (60 s app cache), then apply.sql.
-- Rows already equal to the reviewed list are kept; a differing row aborts.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

${targetsSql}

${resolveAndGuardSeries}

${insertRestrictions}

${allRowsPresent("RESTRICTION_ROWCOUNT")}
commit;
`;

  const apply = `${header(tag, n, episodes, "apply")}
-- In one transaction: write the reviewed restriction row for every work (or
-- verify the row restrictions.sql wrote), then publish exactly what the
-- author's publish flow changes:
--   series   : publication_status 'private' -> 'public', is_public false -> true
--   episodes : posting_status 'draft' -> 'posted', is_published false -> true,
--              posted_at null -> now()
-- Previous values are stored in libread_internal so rollback.sql restores them.
-- Minimum age of restriction rows before publication: ${minAge} s.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';

${targetsSql}

${resolveAndGuardSeries}

create schema if not exists libread_internal;
create table ${seriesSnap} (
  series_id uuid primary key,
  manifest_id text not null unique,
  expected_episodes integer not null,
  is_public_before boolean,
  publication_status_before text not null,
  restriction_inserted boolean not null
);
create table ${episodeSnap} (
  episode_id uuid primary key,
  series_id uuid not null,
  episode_number integer not null,
  is_published_before boolean not null,
  posting_status_before text not null,
  scheduled_for_before timestamptz,
  posted_at_before timestamptz,
  last_edited_at_before timestamptz,
  posted_at_after timestamptz
);
alter table ${seriesSnap} enable row level security;
alter table ${episodeSnap} enable row level security;
revoke all on ${seriesSnap} from public, anon, authenticated;
revoke all on ${episodeSnap} from public, anon, authenticated;

insert into ${seriesSnap}
  (series_id, manifest_id, expected_episodes, is_public_before, publication_status_before, restriction_inserted)
select m.series_id, t.manifest_id, t.expected_episodes, s.is_public, s.publication_status,
       not exists (select 1 from public.series_region_restrictions r where r.series_id = m.series_id)
from pd_region_targets t
join pd_region_series m using (manifest_id)
join public.series s on s.id = m.series_id;

insert into ${episodeSnap}
  (episode_id, series_id, episode_number, is_published_before, posting_status_before,
   scheduled_for_before, posted_at_before, last_edited_at_before)
select e.id, e.series_id, e.episode_number, e.is_published, e.posting_status,
       e.scheduled_for, e.posted_at, e.last_edited_at
from public.episodes e
join ${seriesSnap} t on t.series_id = e.series_id;

do $$ begin
  if (select count(*) from ${seriesSnap}) <> ${n} then
    raise exception '${code}_SERIES_COUNT_MISMATCH';
  end if;
  if (select count(*) from ${episodeSnap}) <> ${episodes} then
    raise exception '${code}_EPISODE_COUNT_MISMATCH';
  end if;
  if exists (
    select 1 from ${episodeSnap}
    where posting_status_before <> 'draft' or is_published_before
       or scheduled_for_before is not null or posted_at_before is not null
  ) then raise exception '${code}_EPISODE_STATE_DRIFT'; end if;
  if exists (
    select 1
    from ${seriesSnap} t
    left join ${episodeSnap} e on e.series_id = t.series_id
    group by t.series_id, t.expected_episodes
    having count(e.episode_id) <> t.expected_episodes
        or min(e.episode_number) <> 1
        or max(e.episode_number) <> t.expected_episodes
  ) then raise exception '${code}_EPISODE_NUMBERING_DRIFT'; end if;
end $$;

-- 1) Restriction rows first (same transaction).
${insertRestrictions}

${allRowsPresent("RESTRICTION_MISSING")}
${
  minAge > 0
    ? `
do $$ begin
  if exists (
    select 1 from ${seriesSnap} t
    join public.series_region_restrictions r on r.series_id = t.series_id
    where r.decided_at > now() - interval '${minAge} seconds'
  ) then raise exception '${code}_RESTRICTION_TOO_RECENT'; end if;
end $$;
`
    : ""
}
-- 2) Publish. Only works that now have the reviewed restriction row.
do $$
declare
  v_series integer;
  v_episodes integer;
begin
  update public.series s
    set publication_status = 'public', is_public = true
  from ${seriesSnap} t
  where s.id = t.series_id
    and s.publication_status = 'private' and s.is_public = false
    and exists (select 1 from public.series_region_restrictions r where r.series_id = s.id);
  get diagnostics v_series = row_count;
  if v_series <> ${n} then
    raise exception '${code}_SERIES_ROWCOUNT_MISMATCH %', v_series;
  end if;

  update public.episodes e
    set posting_status = 'posted', is_published = true, posted_at = now()
  from ${episodeSnap} t
  where e.id = t.episode_id
    and e.posting_status = 'draft' and e.is_published = false and e.posted_at is null;
  get diagnostics v_episodes = row_count;
  if v_episodes <> ${episodes} then
    raise exception '${code}_EPISODE_ROWCOUNT_MISMATCH %', v_episodes;
  end if;

  update ${episodeSnap} t
    set posted_at_after = e.posted_at
  from public.episodes e
  where e.id = t.episode_id;

  if (select count(*) from public.public_episode_work_summaries v
      join ${seriesSnap} t on t.series_id = v.series_id
      where v.episode_count = t.expected_episodes) <> ${n} then
    raise exception '${code}_PUBLIC_VIEW_MISMATCH';
  end if;
  -- No target may be public without its restriction row.
  if exists (
    select 1 from ${seriesSnap} t
    join public.series s on s.id = t.series_id
    left join public.series_region_restrictions r on r.series_id = t.series_id
    where s.publication_status = 'public' and r.series_id is null
  ) then raise exception '${code}_PUBLIC_WITHOUT_RESTRICTION'; end if;
end $$;
commit;

-- After commit: check /works/<id> from an allowed and a blocked country
-- (451 expected outside the list), /search and /sitemap.xml.
`;

  const rollback = `${header(tag, n, episodes, "rollback")}
-- Exact revert of apply.sql: back to private Drafts with every stored previous
-- value, then remove only the restriction rows apply.sql itself inserted (the
-- works are private again by then). Aborts with no change if anything was
-- edited after apply.sql. Resolve such a case by hand; do not force it.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';

select s.id from public.series s
join ${seriesSnap} t on t.series_id = s.id
for update of s;

do $$ begin
  if (select count(*) from ${seriesSnap}) <> ${n}
     or (select count(*) from ${episodeSnap}) <> ${episodes}
     or exists (select 1 from ${seriesSnap} where manifest_id not in (${manifestIdList}))
     or exists (select 1 from ${episodeSnap} e
                where e.series_id not in (select series_id from ${seriesSnap}))
  then raise exception '${code}_ROLLBACK_SNAPSHOT_SCOPE_MISMATCH'; end if;
  if exists (
    select 1 from ${seriesSnap} t
    left join public.series s on s.id = t.series_id
    where s.id is null or s.publication_status <> 'public' or s.is_public is distinct from true
  ) then raise exception '${code}_ROLLBACK_SERIES_STATE_DRIFT'; end if;
  if exists (
    select 1 from ${episodeSnap} t
    left join public.episodes e on e.id = t.episode_id
    where e.id is null
       or e.series_id <> t.series_id
       or e.posting_status <> 'posted' or e.is_published is distinct from true
       or e.scheduled_for is not null
       or t.posted_at_after is null or e.posted_at is distinct from t.posted_at_after
       or e.last_edited_at is distinct from t.last_edited_at_before
  ) then raise exception '${code}_ROLLBACK_EPISODE_STATE_DRIFT'; end if;
  if (select count(*) from public.episodes e
      join ${seriesSnap} t on t.series_id = e.series_id) <> ${episodes} then
    raise exception '${code}_ROLLBACK_EPISODE_SET_CHANGED';
  end if;
end $$;

do $$
declare
  v_series integer;
  v_episodes integer;
begin
  update public.episodes e
    set posting_status = t.posting_status_before,
        is_published = t.is_published_before,
        scheduled_for = t.scheduled_for_before,
        posted_at = t.posted_at_before,
        last_edited_at = t.last_edited_at_before
  from ${episodeSnap} t
  where e.id = t.episode_id and e.posted_at = t.posted_at_after;
  get diagnostics v_episodes = row_count;
  if v_episodes <> ${episodes} then
    raise exception '${code}_ROLLBACK_EPISODE_ROWCOUNT_MISMATCH %', v_episodes;
  end if;

  update public.series s
    set publication_status = t.publication_status_before,
        is_public = t.is_public_before
  from ${seriesSnap} t
  where s.id = t.series_id and s.publication_status = 'public';
  get diagnostics v_series = row_count;
  if v_series <> ${n} then
    raise exception '${code}_ROLLBACK_SERIES_ROWCOUNT_MISMATCH %', v_series;
  end if;

  if exists (select 1 from public.public_episode_work_summaries v
             join ${seriesSnap} t on t.series_id = v.series_id) then
    raise exception '${code}_ROLLBACK_STILL_PUBLIC';
  end if;

  delete from public.series_region_restrictions r
  using ${seriesSnap} t
  where r.series_id = t.series_id and t.restriction_inserted;
end $$;

drop table ${episodeSnap};
drop table ${seriesSnap};
commit;
`;

  return { restrictions, apply, rollback };
}

function main() {
  const args = process.argv.slice(2);
  const tag = args.find((a) => a.startsWith("--tag="))?.slice("--tag=".length) ?? "";
  const out = args.find((a) => a.startsWith("--out="))?.slice("--out=".length) ?? "";
  const minAgeRaw = args
    .find((a) => a.startsWith("--min-restriction-age-seconds="))
    ?.slice("--min-restriction-age-seconds=".length);
  if (!out) throw new Error("--out=<dir> is required");
  const manifestDir = resolve(process.cwd(), "public-domain/manifests");
  let ids = args.filter((a) => !a.startsWith("--"));
  if (args.includes("--all-region-restricted")) {
    if (ids.length > 0) throw new Error("give manifest ids or --all-region-restricted, not both");
    ids = readdirSync(manifestDir)
      .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
      .map((f) => f.slice(0, -5))
      .filter((id) => {
        const raw = JSON.parse(readFileSync(resolve(manifestDir, `${id}.json`), "utf8"));
        return raw.approved === true && raw.region_restriction && raw.import_status !== "not_imported";
      });
  }
  if (ids.length === 0) throw new Error("no manifests selected");
  const targets = ids.sort().map((id) => {
    const result = validateManifest(
      JSON.parse(readFileSync(resolve(manifestDir, `${id}.json`), "utf8"))
    );
    if (!result.ok || !result.manifest) {
      throw new Error(`${id}: invalid manifest: ${result.errors.join("; ")}`);
    }
    return regionPublishTargetFromManifest(result.manifest);
  });
  const sql = buildRegionPublishSql({
    tag,
    targets,
    minRestrictionAgeSeconds: minAgeRaw ? Number(minAgeRaw) : 0,
  });
  mkdirSync(out, { recursive: true });
  writeFileSync(resolve(out, "restrictions.sql"), sql.restrictions, "utf8");
  writeFileSync(resolve(out, "apply.sql"), sql.apply, "utf8");
  writeFileSync(resolve(out, "rollback.sql"), sql.rollback, "utf8");
  console.log(
    `Wrote restrictions.sql, apply.sql, rollback.sql for ${targets.length} works / ${targets.reduce(
      (s, t) => s + t.expectedEpisodes,
      0
    )} chapters to ${out}`
  );
}

if (process.argv[1] && /region-publish-sql\.ts$/.test(process.argv[1])) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
