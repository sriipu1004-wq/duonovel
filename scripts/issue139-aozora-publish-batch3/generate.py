# Issue #139 batch 3: derive the publish SQL from the reviewed batch-2 SQL
# (scripts/issue139-aozora-publish-batch2/) by replacing only the scope:
# series ids, manifest ids, expected episode counts and warnings (from the
# manifests), the 44/410 totals, the snapshot table names and error codes.
#   PYTHONIOENCODING=utf-8 python scripts/issue139-aozora-publish-batch3/generate.py <map.txt>
import json, re, sys

pairs = [p.split(",") for p in open(sys.argv[1], encoding="utf8").read().strip().split(";")]
rows = []
for series_id, manifest_id in pairs:
    m = json.load(open(f"public-domain/manifests/{manifest_id}.json", encoding="utf8"))
    rows.append((series_id, manifest_id, m["chapter_count"], sorted(m["content_warnings"])))
n_series = len(rows)
n_eps = sum(r[2] for r in rows)
assert n_series == 63 and n_eps == 282, (n_series, n_eps)

uuid = r"'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'"
id_list = ",\n             ".join(f"'{r[0]}'" for r in rows)

def values_rows():
    out = []
    for sid, mid, n, w in rows:
        arr = "array[" + ",".join(f"'{x}'" for x in w) + "]::text[]"
        out.append(f"('{sid}'::uuid, '{mid}', {n}, {arr})")
    return ",\n  ".join(out)

for name in ["apply.sql", "rollback.sql"]:
    s = open(f"scripts/issue139-aozora-publish-batch2/{name}", encoding="utf8").read()
    # in (...) id lists
    s = re.sub(r"\(" + uuid + r"(?:,\s*" + uuid + r")+\)", "(" + id_list + ")", s)
    # values rows (series_id, manifest_id, n, warnings)
    s = re.sub(r"\('[0-9a-f-]{36}'::uuid, 'aozora-\d+', \d+, array\[[^\]]*\]::text\[\]\)(?:,\s*\('[0-9a-f-]{36}'::uuid, 'aozora-\d+', \d+, array\[[^\]]*\]::text\[\]\))*",
               values_rows(), s)
    s = s.replace("issue139_publish2_", "issue139_publish3_")
    s = s.replace("ISSUE139_BATCH2_", "ISSUE139_BATCH3_")
    s = re.sub(r"<> 44\b", f"<> {n_series}", s)
    s = re.sub(r"<> 410\b", f"<> {n_eps}", s)
    s = re.sub(r"\b44 Aozora works \(410 chapters\)", f"{n_series} Aozora works ({n_eps} chapters)", s)
    for sid, *_ in rows:
        assert s.count(sid) >= 1, (name, sid)
    leftover = re.findall(r"<> (44|410)\b|publish2|BATCH2", s)
    assert not leftover, (name, leftover)
    header = ("-- GENERATED by scripts/issue139-aozora-publish-batch3/generate.py from the\n"
              "-- batch-2 SQL; only the scope differs (63 works, 282 chapters, PR #219,\n"
              "-- docs/rights/pd-batch-2026-11-aozora-3.md). Owner approval: button\n"
              "-- answer 2026-11-15「公開まで進める (推奨)」.\n")
    open(f"scripts/issue139-aozora-publish-batch3/{name}", "w", encoding="utf8", newline="\n").write(header + s)
print("series", n_series, "episodes", n_eps)
